#pragma once
#include <string>
#include <cstdint>

enum class Side {
    BUY,
    SELL
};

enum class OrderType {
    MARKET,
    LIMIT,
    TRAILING_STOP
};

enum class OrderStatus {
    NEW,
    PARTIALLY_FILLED,
    FILLED,
    CANCELED,
    REJECTED,
    EXPIRED
};

// Represents a price update or a trade execution in the market.
struct MarketTick {
    std::string symbol;
    double price;         // Last trade price (or mid-price)
    double volume;        // Last trade volume
    uint64_t timestamp_ms;
    
    // Level 1 Order Book Data (Optional/0.0 if not provided by the feed)
    double bid_price = 0.0;
    double bid_size = 0.0;
    double ask_price = 0.0;
    double ask_size = 0.0;
};

// Represents an order we want to send to the exchange.
struct OrderRequest {
    std::string client_order_id; // Unique ID generated by the client
    std::string symbol;
    Side side;
    OrderType type;
    double quantity;
    double price; // Relevant only for LIMIT orders
    double trail_price = 0.0;    // For TRAILING_STOP (absolute distance)
    double trail_percent = 0.0;  // For TRAILING_STOP (percentage distance, e.g., 1.0 for 1%)
};

// Represents a notification from the exchange about an order's status change.
struct ExecutionReport {
    std::string order_id;        // ID assigned by the exchange
    std::string client_order_id; // ID assigned by the client
    std::string symbol;
    Side side;
    OrderStatus status;
    double last_quantity; // Quantity filled in this specific update
    double cumulative_quantity; // Total quantity filled so far
    double last_price;    // Price of the last fill
    double avg_price;     // Average price of all fills for this order
    uint64_t timestamp_ms;
};